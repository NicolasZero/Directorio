-- Consolidates directorios and centros_atencion into centros.
-- Back up the database before running. The migration copies and verifies all
-- parent and child rows before dropping the legacy tables, in one transaction.

BEGIN;

CREATE TABLE IF NOT EXISTS centros (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tipo_registro varchar NOT NULL CHECK (tipo_registro IN ('DIRECTORIO', 'MAPA')),
    nombre varchar NOT NULL,
    descripcion text,
    organismo varchar,
    tipo_organismo varchar CHECK (tipo_organismo IN ('INAMUJER', 'MINISTERIO', 'OTRA')),
    direccion varchar,
    telefono varchar,
    correo varchar,
    foto varchar,
    estado_id integer REFERENCES estados(id),
    municipio_id integer REFERENCES municipios(id),
    parroquia_id integer REFERENCES parroquias(id),
    latitud numeric(9, 6) CHECK (latitud BETWEEN -90 AND 90),
    longitud numeric(9, 6) CHECK (longitud BETWEEN -180 AND 180),
    calificacion numeric(2, 1) CHECK (calificacion BETWEEN 0 AND 5),
    horario varchar,
    fuente varchar NOT NULL CHECK (fuente IN ('DIRECTORIO', 'CENTRO_ATENCION', 'ADMIN')),
    fuente_id integer,
    created_at timestamp DEFAULT NOW(),
    CONSTRAINT centros_latitud_longitud_pair CHECK (
        (latitud IS NULL AND longitud IS NULL) OR
        (latitud IS NOT NULL AND longitud IS NOT NULL)
    ),
    CONSTRAINT centros_fuente_id_unique UNIQUE (fuente, fuente_id)
);

CREATE TABLE IF NOT EXISTS servicios_centro (
    id integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY (START WITH 1),
    centro_id integer NOT NULL REFERENCES centros(id) ON DELETE CASCADE,
    servicio varchar NOT NULL,
    created_at timestamp DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS responsables_centro (
    id integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY (START WITH 1),
    centro_id integer NOT NULL REFERENCES centros(id) ON DELETE CASCADE,
    nombre varchar NOT NULL,
    cargo varchar NOT NULL,
    created_at timestamp DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS redes_centro (
    id integer PRIMARY KEY NOT NULL UNIQUE GENERATED ALWAYS AS IDENTITY (START WITH 1),
    centro_id integer NOT NULL REFERENCES centros(id) ON DELETE CASCADE,
    nombre varchar NOT NULL,
    url varchar NOT NULL,
    icono varchar,
    created_at timestamp DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS requisitos_centro (
    id integer PRIMARY KEY NOT NULL UNIQUE GENERATED ALWAYS AS IDENTITY (START WITH 1),
    centro_id integer NOT NULL REFERENCES centros(id) ON DELETE CASCADE,
    requisito varchar NOT NULL,
    created_at timestamp DEFAULT NOW()
);

DO $$
BEGIN
    IF to_regclass('public.directorios') IS NULL
       OR to_regclass('public.centros_atencion') IS NULL THEN
        RAISE EXCEPTION
            'No se encontraron las tablas legacy public.directorios y public.centros_atencion. Esta migracion solo aplica a bases legacy; el esquema unificado ya usa public.centros. No se modifico ningun dato.';
    END IF;

    IF to_regclass('public.servicios_directorio') IS NULL
       OR to_regclass('public.responsables_directorio') IS NULL
       OR to_regclass('public.redes_directorio') IS NULL
       OR to_regclass('public.requisitos_directorio') IS NULL THEN
        RAISE EXCEPTION
            'Faltan tablas relacionadas del esquema legacy. La migracion se cancelo antes de modificar datos.';
    END IF;

    IF EXISTS (SELECT 1 FROM centros)
       OR EXISTS (SELECT 1 FROM servicios_centro)
       OR EXISTS (SELECT 1 FROM responsables_centro)
       OR EXISTS (SELECT 1 FROM redes_centro)
       OR EXISTS (SELECT 1 FROM requisitos_centro) THEN
        RAISE EXCEPTION
            'Las tablas destino ya contienen datos. La migracion se cancelo para evitar duplicados.';
    END IF;
END;
$$;

DROP VIEW IF EXISTS vw_directorio_detalle;
DROP VIEW IF EXISTS vw_directorios_list;

INSERT INTO centros (
    id, tipo_registro, nombre, descripcion, direccion, telefono, correo, foto,
    estado_id, municipio_id, horario, fuente, fuente_id, created_at
)
SELECT
    d.id, 'DIRECTORIO', d.nombre, d.descripcion, d.direccion, d.telefono,
    d.correo, d.foto, d.estado_id, d.municipio_id, d.horario,
    'DIRECTORIO', d.id, d.created_at
FROM directorios d;

INSERT INTO centros (
    id, tipo_registro, nombre, descripcion, organismo, tipo_organismo, direccion,
    estado_id, municipio_id, parroquia_id, latitud, longitud, calificacion,
    fuente, fuente_id, created_at
)
SELECT
    (SELECT COALESCE(MAX(id), 0) FROM directorios) + c.id,
    'MAPA', c.nombre, c.descripcion, c.organismo, c.tipo_organismo, c.direccion,
    e.id, m.id, c.parroquia_id, c.latitud, c.longitud, c.calificacion,
    'CENTRO_ATENCION', c.id, c.created_at
FROM centros_atencion c
JOIN parroquias p ON p.id = c.parroquia_id
JOIN municipios m ON m.id = p.municipio_id
JOIN estados e ON e.id = m.estado_id;

INSERT INTO servicios_centro (id, centro_id, servicio, created_at)
OVERRIDING SYSTEM VALUE
SELECT id, directorio_id, servicio, created_at FROM servicios_directorio;

INSERT INTO responsables_centro (id, centro_id, nombre, cargo, created_at)
OVERRIDING SYSTEM VALUE
SELECT id, directorio_id, nombre, cargo, created_at FROM responsables_directorio;

INSERT INTO redes_centro (id, centro_id, nombre, url, icono, created_at)
OVERRIDING SYSTEM VALUE
SELECT id, directorio_id, nombre, url, icono, created_at FROM redes_directorio;

INSERT INTO requisitos_centro (id, centro_id, requisito, created_at)
OVERRIDING SYSTEM VALUE
SELECT id, directorio_id, requisito, created_at FROM requisitos_directorio;

DO $$
BEGIN
    IF (SELECT count(*) FROM centros WHERE tipo_registro = 'DIRECTORIO') <>
       (SELECT count(*) FROM directorios)
       OR (SELECT count(*) FROM centros WHERE tipo_registro = 'MAPA') <>
       (SELECT count(*) FROM centros_atencion) THEN
        RAISE EXCEPTION 'La cantidad de centros migrados no coincide con las tablas de origen.';
    END IF;

    IF (SELECT count(*) FROM servicios_centro) <>
       (SELECT count(*) FROM servicios_directorio)
       OR (SELECT count(*) FROM responsables_centro) <>
       (SELECT count(*) FROM responsables_directorio)
       OR (SELECT count(*) FROM redes_centro) <>
       (SELECT count(*) FROM redes_directorio)
       OR (SELECT count(*) FROM requisitos_centro) <>
       (SELECT count(*) FROM requisitos_directorio) THEN
        RAISE EXCEPTION 'La cantidad de datos relacionados no coincide con las tablas de origen.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM centros
        WHERE tipo_registro = 'MAPA'
          AND (parroquia_id IS NULL OR municipio_id IS NULL OR estado_id IS NULL
               OR latitud IS NULL OR longitud IS NULL)
    ) THEN
        RAISE EXCEPTION 'Hay sedes georreferenciadas incompletas; se cancela la migracion.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM centros c
        JOIN municipios m ON m.id = c.municipio_id
        WHERE c.tipo_registro = 'DIRECTORIO'
          AND c.estado_id <> m.estado_id
    ) THEN
        RAISE EXCEPTION 'Hay directorios cuyo estado no coincide con su municipio.';
    END IF;
END;
$$;

SELECT setval(
    pg_get_serial_sequence('centros', 'id'),
    COALESCE((SELECT MAX(id) FROM centros), 1),
    EXISTS (SELECT 1 FROM centros)
);

SELECT setval(
    pg_get_serial_sequence('servicios_centro', 'id'),
    COALESCE((SELECT MAX(id) FROM servicios_centro), 1),
    EXISTS (SELECT 1 FROM servicios_centro)
);

SELECT setval(
    pg_get_serial_sequence('responsables_centro', 'id'),
    COALESCE((SELECT MAX(id) FROM responsables_centro), 1),
    EXISTS (SELECT 1 FROM responsables_centro)
);

SELECT setval(
    pg_get_serial_sequence('redes_centro', 'id'),
    COALESCE((SELECT MAX(id) FROM redes_centro), 1),
    EXISTS (SELECT 1 FROM redes_centro)
);

SELECT setval(
    pg_get_serial_sequence('requisitos_centro', 'id'),
    COALESCE((SELECT MAX(id) FROM requisitos_centro), 1),
    EXISTS (SELECT 1 FROM requisitos_centro)
);

DROP TABLE servicios_directorio;
DROP TABLE responsables_directorio;
DROP TABLE redes_directorio;
DROP TABLE requisitos_directorio;
DROP TABLE directorios;
DROP TABLE centros_atencion;

CREATE OR REPLACE VIEW vw_directorios_list AS
SELECT
    c.id,
    c.nombre,
    c.direccion,
    c.telefono,
    c.foto,
    c.correo,
    c.horario,
    m.nombre AS municipio,
    e.nombre AS estado
FROM centros c
JOIN municipios m ON m.id = c.municipio_id
JOIN estados e ON e.id = m.estado_id
WHERE c.tipo_registro = 'DIRECTORIO';

CREATE OR REPLACE VIEW vw_directorio_detalle AS
SELECT
    c.id,
    c.nombre,
    c.descripcion,
    c.direccion,
    c.telefono,
    c.correo,
    c.foto,
    c.horario,
    m.nombre AS municipio,
    e.nombre AS estado,
    (
        SELECT json_agg(servicio ORDER BY created_at)
        FROM servicios_centro sc
        WHERE sc.centro_id = c.id
    ) AS servicios,
    (
        SELECT json_agg(jsonb_build_object('nombre', nombre, 'cargo', cargo) ORDER BY created_at)
        FROM responsables_centro rc
        WHERE rc.centro_id = c.id
    ) AS responsables,
    (
        SELECT json_agg(jsonb_build_object('nombre', nombre, 'url', url, 'icono', icono) ORDER BY created_at)
        FROM redes_centro r
        WHERE r.centro_id = c.id
    ) AS redes
FROM centros c
JOIN municipios m ON m.id = c.municipio_id
JOIN estados e ON e.id = m.estado_id
WHERE c.tipo_registro = 'DIRECTORIO';

COMMIT;
