DO $$
DECLARE
    total_ubicaciones integer;
BEGIN
    SELECT count(*) INTO total_ubicaciones
    FROM parroquias_suministradas s
    JOIN estados e ON upper(e.nombre) = s.estado
    JOIN municipios m ON m.estado_id = e.id AND upper(m.nombre) = s.municipio;

    IF total_ubicaciones <> (SELECT count(*) FROM parroquias_suministradas) THEN
        RAISE EXCEPTION 'No se encontraron todos los estados/municipios de parroquias_suministradas; revise aliases antes de continuar.';
    END IF;
END $$;

INSERT INTO parroquias (nombre, municipio_id)
SELECT DISTINCT s.parroquia, m.id
FROM parroquias_suministradas s
JOIN estados e ON upper(e.nombre) = s.estado
JOIN municipios m ON m.estado_id = e.id AND upper(m.nombre) = s.municipio
ON CONFLICT (municipio_id, nombre) DO NOTHING;

COMMIT;
