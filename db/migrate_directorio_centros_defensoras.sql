-- Dev: asistente | Fecha: 2026-11-27
--
-- - Crea la tabla `defensoras` (una fila por defensora, ligada a su centro por
--   correo y teléfono).
-- - Agrega `foto2` (segunda imagen para el mapa) y columnas de soft-delete en
--   `centros`.
-- - Consolidación de datos: tras crear la tabla, inserta una defensora por cada
--   registro DIRECTORIO existente usando su correo/teléfono actuales.
--   (Es idempotente: no duplica si ya existe.)
--
-- NOTA DE LIMPIEZA (opcional, se deja en comentarios para revisión del admin):
--   Después de verificar los datos, el teléfono/correo de `centros` quedan solo
--   como referencia histórica del primer registro; el dato real de contacto
--   vive en `defensoras`.
-- ============================================================================

BEGIN;

-- 1. Segunda imagen para el mapa -------------------------------------------------
ALTER TABLE centros ADD COLUMN IF NOT EXISTS foto2 varchar;

-- 2. Soft delete ------------------------------------------------------------------
ALTER TABLE centros
ADD COLUMN IF NOT EXISTS eliminado boolean NOT NULL DEFAULT false;

ALTER TABLE centros ADD COLUMN IF NOT EXISTS eliminado_en timestamp;

-- 3. Tabla de defensoras -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS defensoras (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    centro_id integer NOT NULL REFERENCES centros (id) ON DELETE CASCADE,
    correo varchar,
    telefono varchar,
    created_at timestamp DEFAULT NOW(),
    eliminado boolean NOT NULL DEFAULT false,
    eliminado_en timestamp
);

CREATE INDEX IF NOT EXISTS defensoras_centro_idx ON defensoras (centro_id);

CREATE INDEX IF NOT EXISTS centros_eliminado_idx ON centros (eliminado);

-- 4. Consolidación: cada registro DIRECTORIO existente se vuelve una defensora ------
--    Solo si su correo no está ya asignado (idempotente).
INSERT INTO
    defensoras (centro_id, correo, telefono)
SELECT c.id, c.correo, c.telefono
FROM centros c
    LEFT JOIN defensoras d ON d.correo = c.correo
WHERE
    c.tipo_registro = 'DIRECTORIO'
    AND c.correo IS NOT NULL
    AND TRIM(c.correo) <> ''
    AND d.id IS NULL;

COMMIT;